def mk_tx(bl, sep="\n"):
    out = []
    for b in bl:
        if b["type"] == "p":
            out.append(b["text"])
        else:
            for r in b["rows"]:
                s = " ".join(c for c in r if c.strip())
                if s:
                    out.append(s)
    return sep.join(out)


def tx_sep(e):
    """원래 tx 가 줄바꿈으로 이었는지 공백으로 이었는지(자료에 두 방식이 섞여 있음). 같은 방식으로 다시 만든다."""
    for sep in ("\n", " "):
        if e["tx"] == mk_tx(e["bl"], sep):
            return sep
    raise AssertionError(("tx 형식을 알 수 없음", e["ic"]))


def find(J, ic):
    hits = [i for i, e in enumerate(J) if e["b"] == DIV and e["ic"] == ic]
    assert len(hits) == 1, (ic, hits)
    return J[hits[0]]


def split_row(e, bi, ri, c0, values):
    row = e["bl"][bi]["rows"][ri]
    vals = values.split()
    assert c0 + len(vals) == len(row), (e["ic"], bi, ri, len(row))
    before = "".join(row[c0:])
    assert before == "".join(vals), (e["ic"], bi, ri, before)       # 나누기만: 글자 그대로
    row[c0:] = vals


def merge_bolt_beating(e):
    """13-5-8 Bolt Beating: '0.097' 줄 + 값 줄 + '5' 줄 → 값 줄 하나(0.0975 × 8)."""
    rows = e["bl"][3]["rows"]
    for top, mid, bot, label in ((36, 37, 38, "플랜트"), (40, 41, 42, "특별인부")):
        assert rows[top][6] == "0.097" * 6 and not any(c for k, c in enumerate(rows[top]) if k != 6)
        assert rows[mid][1] == label and rows[mid][3] == rows[mid][10] == "0.0975" and not any(rows[mid][4:10])
        assert rows[bot][4:10] == ["5"] * 6 and not any(rows[bot][:4] + rows[bot][10:])
        rows[mid][3:11] = ["0.0975"] * 8
    for k in (42, 40, 38, 36):
        del rows[k]


def main(src, dst):
    J = json.load(open(src, encoding="utf-8"))
    n0 = len(J)
    touched = {}
    for ic, bi, ri, c0, values in SPLITS:
        e = find(J, ic)
        if ic not in touched:
            touched[ic] = (e, tx_sep(e))
        split_row(e, bi, ri, c0, values)
    merge_bolt_beating(find(J, "13-5-8"))
    for e, sep in touched.values():
        e["tx"] = mk_tx(e["bl"], sep)
    assert len(J) == n0
    # 원본과 같은 형식(한 줄, ensure_ascii=False)으로 저장
    with open(dst, "w", encoding="utf-8", newline="") as f:
        f.write(json.dumps(J, ensure_ascii=False))
    print(f"{len(SPLITS)}행 나눔, Bolt Beating 2행 합침 → {', '.join(touched)}")


